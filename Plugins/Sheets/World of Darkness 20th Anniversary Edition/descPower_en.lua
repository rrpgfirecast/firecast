Sense the Beast


This first effect of Animalism can be a trump card in the hands of manipulative vampires. Whoever has it gains the ability to concentrate on the Beast of a mortal or animal, perceiving that target's emotional ripples. This power can only be used on creatures that have a Beast. Demons or some Spectres may be immune to this power, making them unreadable.

System: There is no cost, only a roll. The character must concentrate and roll Perception + Alertness (difficulty 8). With a single success, they gain access to that person's dominant emotion, although the stronger the emotion in the target, the lower the difficulty to perceive it. This lets the character know the best way to deal with that target. The emotions in question can vary: anger, stress, happiness, fear. It is as if the vampire smelled that target's emotion, just as an animal would on a hunt.

Unlike Auspex, this power does not let the character see but rather feel the target's emotions within themselves. The one flaw of this power is that the connection can be harmful enough to pass on part of the emotions being felt. Storytellers should consider penalties depending on the emotion felt. Characters sensing anger could raise the difficulty of Self-Control by +2, while characters sensing coldness could raise Conscience rolls by +2. The felt emotion lasts for one scene, but the character can ignore it at a cost of one Willpower point. Using this power on characters in frenzy automatically calls for a Self-Control roll, difficulty 8, for the character not to give in to rage.

The Storyteller should be the final arbiter of the effect suffered from the emotions felt, but must not forget that just as the character can be harmed, they may also benefit from the use of this power.]==],
