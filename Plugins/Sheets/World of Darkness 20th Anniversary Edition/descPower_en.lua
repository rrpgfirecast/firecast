Aura Perception


The true color of the soul is revealed to the vampire with this level of sight. What they see lies outside the physical. They see strong emotions, lost thoughts, or dark memories that have tinted a person's nature. The practitioner's mind translates the impressions they get from another person's soul as colors, temperatures, or even scents. The impressions and feelings of other people's souls can be interpreted, but never translated in a universally correct way.

