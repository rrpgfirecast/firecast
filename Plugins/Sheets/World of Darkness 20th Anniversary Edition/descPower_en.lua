Although animals may carry out dangerous or even potentially deadly tasks for Cainites, they will not commit directly suicidal tasks, nor violate their basic biological natures. Cowardly animals given guard duty will not engage and fight an intruder, for example. They may run to their master and report the threat, however. Successes determine the animal's dedication to the cause. A single success ensures the animal's compliance for the current scene. Three successes ensure a regular task for a week or more. Five successes demand indefinite loyalty.]==],
