Feral Whispers


Feral Whispers lays a foundation on which many of the other powers of Animalism are built. The vampire's Beast reaches out and touches an animal's mind, easing communication between the Cainite and the lesser creature. With this power, the vampire speaks or imitates the animal's native sounds, and the animal understands. The vampire understands the ideas the animal expresses. In addition, the animal may follow the vampire's wishes if the vampire gives a convincing command.

