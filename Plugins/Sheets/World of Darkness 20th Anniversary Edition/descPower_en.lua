Taint with Blood


Traveling Cainites always use a great variety of animals to help them hunt or send messages. The most loyal are ghouls held by the blood bond. Vampires who have this power have learned ways to taint natural sources, invoking strength and loyalty from the animals that feed there. By mixing their vitae with the precious waters of a lake or oasis, all of the vampire's servants who feed there will develop some loyalty to the vampire. Even if this is not enough to create the Blood Bond or turn a mortal into a ghoul, they will still be more faithful to the vampire.

